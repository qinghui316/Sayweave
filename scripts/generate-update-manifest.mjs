import {createHash} from 'node:crypto';
import {readFile,writeFile,readdir,mkdir} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {releaseIdentity,verifyBuild,releaseNotes} from './release-validation.mjs';
const root=process.cwd(),pkg=JSON.parse(await readFile('package.json','utf8'));
const identity=releaseIdentity(pkg.version,process.env.SAYWEAVE_RELEASE_TAG,process.env.SAYWEAVE_RELEASE_COMMIT);
const config=JSON.parse(await readFile('src-tauri/tauri.conf.json','utf8'));
const lock=JSON.parse(await readFile('package-lock.json','utf8'));
const rust=(await readFile('src-tauri/Cargo.toml','utf8')).match(/^version = "([^"]+)"/m)?.[1];
const rustLock=(await readFile('src-tauri/Cargo.lock','utf8')).match(/\[\[package\]\]\r?\nname = "sayweave"\r?\nversion = "([^"]+)"/)?.[1];
verifyBuild(identity,root,[config.version,lock.version,lock.packages[''].version,rust,rustLock]);
const output=resolve(root,process.env.SAYWEAVE_RELEASE_DIR??'release/sayweave'),nsis=resolve(root,'src-tauri/target/release/bundle/nsis');
const files=await readdir(nsis),installer=identity.installer,signature=`${installer}.sig`;
if(!files.includes(installer)||!files.includes(signature))throw new Error('Exact signed NSIS installer missing');
const bytes=await readFile(join(nsis,installer));
const noteData=JSON.parse(await readFile(`release-notes/${identity.tag}.json`,'utf8'));
if(noteData.version!==identity.version)throw new Error('Release notes version differs');
const notes=releaseNotes(noteData);
const sha512=createHash('sha512').update(bytes).digest('base64');
const manifest={version:pkg.version,notes,pub_date:new Date().toISOString(),platforms:{'windows-x86_64':{signature:(await readFile(join(nsis,signature),'utf8')).trim(),url:`https://github.com/qinghui316/Sayweave/releases/download/${identity.tag}/${installer}`,installerSize:bytes.length,installerSha512:sha512}}};
await mkdir(output,{recursive:true});
if((await readdir(output)).length)throw new Error('Release output must be empty; never overwrite assets');
await writeFile(join(output,'latest.json'),JSON.stringify(manifest,null,2)+'\n','utf8');
await writeFile(join(output,installer),bytes);
await writeFile(join(output,signature),await readFile(join(nsis,signature)));
const receipt={schemaVersion:1,...identity,installerSize:bytes.length,installerSha512:sha512,generatedAt:new Date().toISOString()};
await writeFile(join(output,'release-receipt.json'),JSON.stringify(receipt,null,2)+'\n','utf8');
const names=[installer,signature,'latest.json','release-receipt.json'];
const sums=await Promise.all(names.map(async name=>`${createHash('sha256').update(await readFile(join(output,name))).digest('hex')}  ${name}`));
await writeFile(join(output,'SHA256SUMS.txt'),sums.join('\n')+'\n','utf8');
await writeFile(resolve(root,'release/release-notes.md'),notes,'utf8');
console.log(`Generated release ${identity.tag} at ${identity.commit}`);
