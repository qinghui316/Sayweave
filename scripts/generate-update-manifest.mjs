import {createHash} from 'node:crypto';
import {readFile,writeFile,stat} from 'node:fs/promises';
import {join,resolve} from 'node:path';
const root=process.cwd();
const pkg=JSON.parse(await readFile(resolve(root,'package.json'),'utf8'));
const tag=process.env.SAYWEAVE_RELEASE_TAG??`v${pkg.version}`;
const output=resolve(root,process.env.SAYWEAVE_RELEASE_DIR??'release/sayweave');
const nsis=resolve(root,'src-tauri/target/release/bundle/nsis');
const files=await (await import('node:fs/promises')).readdir(nsis);
const installer=files.find(name=>/setup.*\.exe$/i.test(name));
if(!installer)throw new Error('NSIS installer not found');
const signature=`${installer}.sig`;
if(!files.includes(signature))throw new Error('NSIS updater signature not found');
const bytes=await readFile(join(nsis,installer));
const sha512=createHash('sha512').update(bytes).digest('base64');
const manifest={version:pkg.version,notes:`Sayweave ${pkg.version}`,pub_date:new Date().toISOString(),platforms:{'windows-x86_64':{signature:(await readFile(join(nsis,signature),'utf8')).trim(),url:`https://github.com/qinghui316/Sayweave/releases/download/${tag}/${installer}`}}};
await (await import('node:fs/promises')).mkdir(output,{recursive:true});
await writeFile(join(output,'latest.json'),JSON.stringify(manifest,null,2)+'\n','utf8');
await writeFile(join(output,installer),bytes);
await writeFile(join(output,signature),await readFile(join(nsis,signature)));
const receipt={schemaVersion:1,version:pkg.version,tag,commit:process.env.SAYWEAVE_RELEASE_COMMIT??'unknown',installer,installerSize:bytes.length,installerSha512:sha512,generatedAt:new Date().toISOString()};
await writeFile(join(output,'release-receipt.json'),JSON.stringify(receipt,null,2)+'\n','utf8');
const names=[installer,signature,'latest.json','release-receipt.json'];const sums=[];
for(const name of names)sums.push(`${createHash('sha256').update(await readFile(join(output,name))).digest('hex')}  ${name}`);
await writeFile(join(output,'SHA256SUMS.txt'),sums.join('\n')+'\n','utf8');
console.log(`Generated Sayweave updater manifest for ${pkg.version}: ${installer} (${(await stat(join(output,installer))).size} bytes)`);
