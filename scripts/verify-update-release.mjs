import {spawnSync} from 'node:child_process';
import {readFile,readdir} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {releaseIdentity,verifyBuild,validateRelease} from './release-validation.mjs';
const root=process.cwd(),dir=resolve(root,process.env.SAYWEAVE_RELEASE_DIR??'release/sayweave');
const pkg=JSON.parse(await readFile('package.json','utf8'));
const identity=releaseIdentity(pkg.version,process.env.SAYWEAVE_RELEASE_TAG,process.env.SAYWEAVE_RELEASE_COMMIT);
const config=JSON.parse(await readFile('src-tauri/tauri.conf.json','utf8')),lock=JSON.parse(await readFile('package-lock.json','utf8'));
const rust=(await readFile('src-tauri/Cargo.toml','utf8')).match(/^version = "([^"]+)"/m)?.[1];
const rustLock=(await readFile('src-tauri/Cargo.lock','utf8')).match(/\[\[package\]\]\r?\nname = "sayweave"\r?\nversion = "([^"]+)"/)?.[1];
verifyBuild(identity,root,[config.version,lock.version,lock.packages[''].version,rust,rustLock]);
const names=await readdir(dir);
if(names.some(name=>! /^[A-Za-z0-9_.-]+$/.test(name)))throw new Error('Invalid asset name');
const assets=new Map(await Promise.all(names.map(async name=>[name,await readFile(join(dir,name))])));
const manifest=JSON.parse(assets.get('latest.json')),receipt=JSON.parse(assets.get('release-receipt.json'));
validateRelease(identity,manifest,receipt,assets);
const publicKey=config.plugins?.updater?.pubkey;if(typeof publicKey!=='string'||!publicKey)throw new Error('Updater public key missing');
const verify=spawnSync('cargo',['run','--quiet','--manifest-path','src-tauri/Cargo.toml','--bin','verify-update-signature','--',publicKey,join(dir,identity.installer),join(dir,`${identity.installer}.sig`),identity.version],{cwd:root,encoding:'utf8',stdio:['ignore','pipe','pipe'],windowsHide:true});
if(verify.status!==0)throw new Error(`Updater signature/version verification failed: ${verify.stderr||verify.stdout}`);
console.log(`Verified release ${identity.tag} at ${identity.commit}`);
